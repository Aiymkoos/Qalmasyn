create table if not exists public.offers (
  id bigint generated by default as identity primary key,
  restaurant text not null check (char_length(restaurant) between 1 and 80),
  dish text not null check (char_length(dish) between 1 and 100),
  category text not null check (category in ('bakery','cafe','grocery','dessert','meal')),
  old_price integer not null check (old_price > 0),
  price integer not null check (price > 0),
  floor integer check (floor is null or floor > 0),
  portions integer not null check (portions >= 0 and portions <= 999),
  pickup_start time not null,
  pickup time not null,
  address text not null,
  district text not null check (district in ('center','southeast','mikhailovka')),
  photo text,
  description text not null,
  created_at timestamptz not null default now(),
  check (price < old_price),
  check (floor is null or floor < price),
  check (pickup > pickup_start)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  offer_id bigint not null references public.offers(id),
  code text not null unique,
  guest_name text not null,
  phone text not null,
  price integer not null check (price > 0),
  created_at timestamptz not null default now()
);

alter table public.offers enable row level security;
alter table public.bookings enable row level security;
create policy "public can read offers" on public.offers for select using (true);
create policy "public can add offers" on public.offers for insert with check (true);

-- The function changes availability and creates the reservation atomically.
create or replace function public.create_booking(p_offer_id bigint,p_guest_name text,p_phone text,p_price integer,p_code text)
returns table(code text) language plpgsql security definer set search_path=public as $$
begin
  update offers set portions=portions-1 where id=p_offer_id and portions>0;
  if not found then raise exception 'Offer is no longer available'; end if;
  insert into bookings(offer_id,code,guest_name,phone,price) values(p_offer_id,p_code,p_guest_name,p_phone,p_price);
  return query select p_code;
end; $$;
grant execute on function public.create_booking(bigint,text,text,integer,text) to anon;

create or replace function public.cancel_booking(p_code text)
returns void language plpgsql security definer set search_path=public as $$
declare booking_offer bigint;
begin
  delete from bookings where code=p_code returning offer_id into booking_offer;
  if booking_offer is not null then update offers set portions=portions+1 where id=booking_offer; end if;
end; $$;
grant execute on function public.cancel_booking(text) to anon;

