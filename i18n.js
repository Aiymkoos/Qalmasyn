try { if (localStorage.getItem('qalmasyn-lang') === 'kk') lang = 'kk'; } catch {}
const translated = [];
function toKk(text) {
  const t = text.trim();
  if (!t) return null;
  if (Object.prototype.hasOwnProperty.call(KK_EXACT, t)) return text.replace(t, KK_EXACT[t]);
  for (const [re, rep] of KK_RULES) if (re.test(t)) return text.replace(t, t.replace(re, rep));
  return null;
}
function translateNode(root) {
  if (root.nodeType === 3) {
    const result = toKk(root.nodeValue);
    if (result !== null && result !== root.nodeValue) { translated.push([root, null, root.nodeValue]); root.nodeValue = result; }
    return;
  }
  if (root.nodeType !== 1) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let node = walker.currentNode; node; node = walker.nextNode()) {
    if (node.nodeType === 3) {
      if (/^(SCRIPT|STYLE|TEXTAREA)$/.test(node.parentNode.tagName)) continue;
      translateNode(node);
    } else {
      for (const attr of ['placeholder', 'aria-label', 'title']) {
        const value = node.getAttribute(attr);
        const result = value && toKk(value);
        if (result) { translated.push([node, attr, value]); node.setAttribute(attr, result); }
      }
    }
  }
}
function applyLang(next) {
  lang = next === 'kk' ? 'kk' : 'ru';
  try { localStorage.setItem('qalmasyn-lang', lang); } catch {}
  document.documentElement.lang = lang;
  for (const [node, attr, original] of translated) {
    if (!node.isConnected) continue;
    if (attr) node.setAttribute(attr, original); else node.nodeValue = original;
  }
  translated.length = 0;
  if (lang === 'kk') translateNode(document.body);
  document.querySelectorAll('[data-lang]').forEach(button => button.setAttribute('aria-pressed', button.dataset.lang === lang));
}
new MutationObserver(mutations => {
  if (lang !== 'kk') return;
  for (const m of mutations) {
    m.addedNodes.forEach(translateNode);
    if (m.type === 'characterData') translateNode(m.target);
  }
}).observe(document.body, {childList: true, subtree: true, characterData: true});
applyLang(lang);
